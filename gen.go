package toolreview

import (
	"bytes"
	"fmt"
	"go/format"
	"io"
	"sort"
	"strconv"
	"strings"
)

// WriteGo writes m as Go source declaring `var <name> = toolreview.Manifest{…}`
// in package pkg, so a program carries its verdicts compiled in.
func WriteGo(w io.Writer, pkg, name, source string, m Manifest) error {
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by toolreview gen; DO NOT EDIT.\n\n")
	fmt.Fprintf(&b, "package %s\n\n", pkg)
	fmt.Fprintf(&b, "import \"github.com/omniaura/toolreview\"\n\n")
	fmt.Fprintf(&b, "// %s holds the %d %s verdicts reviewed under %s.\n", name, len(m.Entries), oneLine(source), oneLine(m.Policy))
	fmt.Fprintf(&b, "var %s = toolreview.Manifest{\n", name)
	fmt.Fprintf(&b, "Policy: %s,\n", strconv.Quote(m.Policy))
	fmt.Fprintf(&b, "Model: %s,\n", strconv.Quote(m.Model))
	fmt.Fprintf(&b, "Entries: map[string]toolreview.Entry{\n")
	keys := make([]string, 0, len(m.Entries))
	for k := range m.Entries {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	for _, k := range keys {
		e := m.Entries[k]
		policy := ""
		if e.Policy != "" {
			policy = "Policy: " + strconv.Quote(e.Policy) + ", "
		}
		fmt.Fprintf(&b, "%s: {%sFingerprint: %s, Class: %s, Declared: %s, Risk: %s},\n",
			strconv.Quote(k), policy, strconv.Quote(e.Fingerprint), classIdent(e.Class), classIdent(e.Declared),
			strconv.FormatFloat(e.Risk, 'f', -1, 64))
	}
	fmt.Fprintf(&b, "},\n}\n")
	src, err := format.Source(b.Bytes())
	if err != nil {
		return fmt.Errorf("toolreview: format generated source: %w", err)
	}
	_, err = w.Write(src)
	return err
}

func oneLine(s string) string {
	return strings.Join(strings.Fields(s), " ")
}

func classIdent(c Class) string {
	switch c {
	case Read:
		return "toolreview.Read"
	case Write:
		return "toolreview.Write"
	case Outbound:
		return "toolreview.Outbound"
	case Destructive:
		return "toolreview.Destructive"
	default:
		return "toolreview.Unknown"
	}
}
