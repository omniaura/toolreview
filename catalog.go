package toolreview

import (
	"context"
	"errors"
	"sync"
	"time"
)

// Store persists verdicts. Sources partition keys: "composio", "mcp:<server>".
type Store interface {
	// Load returns the stored verdicts for keys; a missing key is absent.
	Load(ctx context.Context, source string, keys []string) (map[string]Verdict, error)
	// Save stores v, replacing any verdict for the same source and key.
	Save(ctx context.Context, source string, v Verdict) error
}

// Entry is one verdict in a Manifest: the offline form a program can compile
// in, so a catalog has verdicts before its first review and while the model or
// the database is unreachable.
type Entry struct {
	// Policy is the entry's policy when it differs from the manifest's.
	Policy      string
	Fingerprint string
	Class       Class
	Declared    Class
	Risk        float64
}

// Manifest is a set of verdicts for one source, generated by
// `toolreview gen` from a review run.
type Manifest struct {
	Policy  string
	Model   string
	Entries map[string]Entry
}

// ManifestOf builds a manifest from verdicts. Policies are the verdicts' own,
// never this package's: regenerating old verdicts under a newer policy must
// leave them stale. The manifest's Policy is the most common one; an entry of
// another policy records its own.
func ManifestOf(verdicts []Verdict) Manifest {
	m := Manifest{Entries: make(map[string]Entry, len(verdicts))}
	counts := map[string]int{}
	for _, v := range verdicts {
		counts[v.Policy]++
		if counts[v.Policy] > counts[m.Policy] || (counts[v.Policy] == counts[m.Policy] && v.Policy < m.Policy) {
			m.Policy = v.Policy
		}
	}
	for i, v := range verdicts {
		// Model is provenance only; a run that mixed models names none.
		if i == 0 {
			m.Model = v.Model
		} else if v.Model != m.Model {
			m.Model = ""
			break
		}
	}
	for _, v := range verdicts {
		e := Entry{Fingerprint: v.Fingerprint, Class: v.Class, Declared: v.Declared, Risk: round3(v.Risk())}
		if v.Policy != m.Policy {
			e.Policy = v.Policy
			if e.Policy == "" {
				e.Policy = "unknown"
			}
		}
		m.Entries[v.Key] = e
	}
	return m
}

func (m Manifest) verdict(key string) (Verdict, bool) {
	e, ok := m.Entries[key]
	if !ok || !e.Class.Valid() {
		return Verdict{}, false
	}
	policy := m.Policy
	if e.Policy != "" {
		policy = e.Policy
	}
	return Verdict{Key: key, Fingerprint: e.Fingerprint, Policy: policy, Model: m.Model, Class: e.Class, Declared: e.Declared}, true
}

// Catalog serves verdicts on the request path without calling the model, and
// reviews what it has not seen in the background.
//
// Lookup order is memory, then Store, then the source's compiled Manifest. A
// verdict whose tool has since changed (or whose policy is older) is still
// served, marked Stale, and the tool is queued for review: it only ever adds
// caution, so the old answer is safer than none. A tool with no verdict at all
// is queued and absent from the result, which callers treat as "not reviewed",
// i.e. the provider's label alone.
//
// Drain runs the queue; call it from a periodic task. Review reviews one tool
// synchronously, for a caller that can afford one model call (~200ms) before
// acting, such as the first call of a tool from a newly connected MCP server.
type Catalog struct {
	reviewer  *Reviewer
	store     Store
	fallbacks map[string]Manifest
	onError   func(source, key string, err error)
	now       func() time.Time

	mu       sync.Mutex
	cache    map[catalogKey]Verdict
	checked  map[catalogKey]time.Time
	queue    map[catalogKey]queued
	failures map[catalogKey]failure
	order    []catalogKey
	maxQueue int
	maxCache int
}

type catalogKey struct{ source, key string }

type queued struct {
	tool Tool
}

// failure remembers a tool whose review keeps failing, across dequeues, so the
// request path cannot re-queue it into a retry loop.
type failure struct {
	until       time.Time
	fingerprint string
	attempts    int
}

// recheckStoreAfter is how long a key the store did not have (or had stale) is
// served from memory before the store is asked again, so another replica's
// review is picked up without a query per lookup.
const recheckStoreAfter = time.Minute

// maxAttempts is how many failed reviews in a row move a tool to the long
// backoff (failedBackoff) instead of the short one.
const maxAttempts = 3

// failedBackoff is how long a tool whose review failed maxAttempts times is
// left alone. A changed tool (new fingerprint) is retried at once.
const failedBackoff = time.Hour

// CatalogOption configures a Catalog.
type CatalogOption func(*Catalog)

// WithFallback compiles in a manifest for source.
func WithFallback(source string, m Manifest) CatalogOption {
	return func(c *Catalog) { c.fallbacks[source] = m }
}

// WithErrorHandler receives store and review failures. Lookups never fail;
// they degrade to the next source.
func WithErrorHandler(fn func(source, key string, err error)) CatalogOption {
	return func(c *Catalog) { c.onError = fn }
}

// WithLimits bounds the queue and the in-memory cache.
func WithLimits(maxQueue, maxCache int) CatalogOption {
	return func(c *Catalog) {
		if maxQueue > 0 {
			c.maxQueue = maxQueue
		}
		if maxCache > 0 {
			c.maxCache = maxCache
		}
	}
}

// WithClock replaces time.Now (tests).
func WithClock(now func() time.Time) CatalogOption {
	return func(c *Catalog) { c.now = now }
}

// NewCatalog returns a Catalog. reviewer may be nil (lookups and fallbacks
// only); store may be nil (memory only).
func NewCatalog(reviewer *Reviewer, store Store, opts ...CatalogOption) *Catalog {
	c := &Catalog{
		reviewer:  reviewer,
		store:     store,
		fallbacks: map[string]Manifest{},
		now:       time.Now,
		cache:     map[catalogKey]Verdict{},
		checked:   map[catalogKey]time.Time{},
		queue:     map[catalogKey]queued{},
		failures:  map[catalogKey]failure{},
		maxQueue:  20000,
		maxCache:  100000,
	}
	for _, opt := range opts {
		opt(c)
	}
	return c
}

// Verdicts returns the best verdict available for each tool, keyed by
// Tool.Key, without calling the model. Every verdict's Declared is the tool's
// current provider label. Tools without a current verdict are queued.
func (c *Catalog) Verdicts(ctx context.Context, source string, tools []Tool) map[string]Verdict {
	out := make(map[string]Verdict, len(tools))
	if c == nil || len(tools) == 0 {
		return out
	}
	now := c.now()
	var ask []string
	c.mu.Lock()
	for _, t := range tools {
		k := catalogKey{source, t.Key}
		if v, ok := c.cache[k]; ok && v.Current(t) {
			out[t.Key] = withDeclared(v, t)
			continue
		}
		if at, ok := c.checked[k]; ok && now.Sub(at) < recheckStoreAfter {
			continue
		}
		ask = append(ask, t.Key)
	}
	c.mu.Unlock()

	var stored map[string]Verdict
	if len(ask) > 0 && c.store != nil {
		var err error
		stored, err = c.store.Load(ctx, source, ask)
		if err != nil {
			c.report(source, "", err)
			stored = nil
		}
	}
	asked := make(map[string]bool, len(ask))
	for _, key := range ask {
		asked[key] = true
	}

	c.mu.Lock()
	defer c.mu.Unlock()
	for _, t := range tools {
		if _, done := out[t.Key]; done {
			continue
		}
		k := catalogKey{source, t.Key}
		if asked[t.Key] {
			if len(c.checked) >= c.maxCache {
				clear(c.checked)
			}
			c.checked[k] = now
			if v, ok := stored[t.Key]; ok && v.Class.Valid() {
				// A stale stored verdict never replaces a cached one: with
				// several writers it may be older and less cautious.
				if _, cached := c.cache[k]; !cached || v.Current(t) {
					c.remember(k, v)
				}
			}
		}
		v, ok := c.cache[k]
		if fb, fok := c.fallbacks[source].verdict(t.Key); fok && (!ok || (!v.Current(t) && fb.Current(t))) {
			v, ok = fb, true
		}
		if ok && v.Current(t) {
			c.remember(k, v)
			out[t.Key] = withDeclared(v, t)
			continue
		}
		if ok {
			v.Stale = true
			out[t.Key] = withDeclared(v, t)
		}
		c.enqueueLocked(k, t)
	}
	return out
}

// Review returns a current verdict for t, calling the model if there is none.
// On failure it returns the best stale verdict it has (Stale set), or none,
// with the error; the tool stays queued.
func (c *Catalog) Review(ctx context.Context, source string, t Tool) (Verdict, error) {
	if c == nil {
		return Verdict{Declared: t.Declared}, errNoReviewer
	}
	got := c.Verdicts(ctx, source, []Tool{t})
	best, have := got[t.Key]
	if have && !best.Stale {
		return best, nil
	}
	k := catalogKey{source, t.Key}
	c.mu.Lock()
	backedOff := c.backedOffLocked(k, t)
	c.mu.Unlock()
	if backedOff {
		return withDeclared(best, t), ErrBackoff
	}
	v, err := c.reviewAndSave(ctx, source, t)
	c.mu.Lock()
	defer c.mu.Unlock()
	if err != nil {
		if !cancelled(err) {
			c.failedLocked(k, t)
		}
		return withDeclared(best, t), err
	}
	delete(c.queue, k)
	delete(c.failures, k)
	return withDeclared(v, t), nil
}

// Enqueue queues tools for review. Tools that turn out to have a current
// verdict when the queue runs are skipped without a model call.
func (c *Catalog) Enqueue(source string, tools ...Tool) {
	if c == nil {
		return
	}
	c.mu.Lock()
	defer c.mu.Unlock()
	for _, t := range tools {
		k := catalogKey{source, t.Key}
		if v, ok := c.cache[k]; ok && v.Current(t) {
			continue
		}
		c.enqueueLocked(k, t)
	}
}

func (c *Catalog) enqueueLocked(k catalogKey, t Tool) {
	if t.Key == "" || t.Name == "" {
		return
	}
	if c.backedOffLocked(k, t) {
		return
	}
	if len(c.order) > 2*len(c.queue)+64 {
		c.compactLocked()
	}
	if q, ok := c.queue[k]; ok {
		q.tool = t
		c.queue[k] = q
		return
	}
	if len(c.queue) >= c.maxQueue {
		return
	}
	c.queue[k] = queued{tool: t}
	c.order = append(c.order, k)
}

// backedOffLocked reports whether t's last reviews failed recently enough
// that it must not be sent to the model again yet.
func (c *Catalog) backedOffLocked(k catalogKey, t Tool) bool {
	f, ok := c.failures[k]
	return ok && f.fingerprint == Fingerprint(t) && c.now().Before(f.until)
}

func (c *Catalog) compactLocked() {
	live := c.order[:0]
	for _, k := range c.order {
		if _, ok := c.queue[k]; ok {
			live = append(live, k)
		}
	}
	clear(c.order[len(live):])
	c.order = live
}

// failedLocked records a failed review and its backoff: a minute per attempt,
// then failedBackoff once the attempts run out.
func (c *Catalog) failedLocked(k catalogKey, t Tool) {
	if t.Key == "" || t.Name == "" {
		return
	}
	fp := Fingerprint(t)
	f := c.failures[k]
	if f.fingerprint != fp {
		f = failure{fingerprint: fp}
	}
	f.attempts++
	wait := time.Duration(f.attempts) * time.Minute
	if f.attempts >= maxAttempts {
		wait = failedBackoff
	}
	f.until = c.now().Add(wait)
	if len(c.failures) >= c.maxQueue {
		now := c.now()
		for fk, f := range c.failures {
			if !now.Before(f.until) {
				delete(c.failures, fk)
			}
		}
		if len(c.failures) >= c.maxQueue {
			clear(c.failures)
		}
	}
	c.failures[k] = f
}

// Pending is the number of queued tools.
func (c *Catalog) Pending() int {
	if c == nil {
		return 0
	}
	c.mu.Lock()
	defer c.mu.Unlock()
	return len(c.queue)
}

// DrainStats reports one Drain.
type DrainStats struct {
	Reviewed int
	Current  int
	Failed   int
	Raised   int
	Cost     float64
}

// Drain reviews up to max queued tools with concurrency calls in flight. A
// tool another replica has already reviewed is taken from the store instead.
func (c *Catalog) Drain(ctx context.Context, max, concurrency int) DrainStats {
	var stats DrainStats
	if c == nil || c.reviewer == nil {
		return stats
	}
	type item struct {
		k catalogKey
		q queued
	}
	c.mu.Lock()
	var batch []item
	rest := c.order[:0]
	for _, k := range c.order {
		q, ok := c.queue[k]
		if !ok {
			continue
		}
		if c.backedOffLocked(k, q.tool) {
			// Queued before its review failed elsewhere; Verdicts re-queues
			// it once the backoff ends.
			delete(c.queue, k)
			continue
		}
		if len(batch) < max {
			batch = append(batch, item{k, q})
			delete(c.queue, k)
			continue
		}
		rest = append(rest, k)
	}
	clear(c.order[len(rest):])
	c.order = rest
	c.mu.Unlock()

	var mu sync.Mutex
	sem := make(chan struct{}, max1(concurrency))
	var wg sync.WaitGroup
	for _, it := range batch {
		if ctx.Err() != nil {
			c.requeue(it.k, it.q)
			continue
		}
		sem <- struct{}{}
		wg.Go(func() {
			defer func() { <-sem }()
			if c.store != nil {
				if stored, err := c.store.Load(ctx, it.k.source, []string{it.k.key}); err == nil {
					if v, ok := stored[it.k.key]; ok && v.Current(it.q.tool) {
						c.mu.Lock()
						c.remember(it.k, v)
						c.mu.Unlock()
						mu.Lock()
						stats.Current++
						mu.Unlock()
						return
					}
				}
			}
			v, err := c.reviewAndSave(ctx, it.k.source, it.q.tool)
			mu.Lock()
			defer mu.Unlock()
			stats.Cost += v.Cost
			if err != nil {
				stats.Failed++
				if cancelled(err) {
					// The run ended, not the review: try again next time.
					c.requeue(it.k, it.q)
					return
				}
				c.mu.Lock()
				c.failedLocked(it.k, it.q.tool)
				c.mu.Unlock()
				return
			}
			c.mu.Lock()
			delete(c.failures, it.k)
			c.mu.Unlock()
			stats.Reviewed++
			if withDeclared(v, it.q.tool).Raised() {
				stats.Raised++
			}
		})
	}
	wg.Wait()
	return stats
}

func (c *Catalog) requeue(k catalogKey, q queued) {
	c.mu.Lock()
	defer c.mu.Unlock()
	if _, ok := c.queue[k]; ok {
		return
	}
	c.queue[k] = q
	c.order = append(c.order, k)
}

func (c *Catalog) reviewAndSave(ctx context.Context, source string, t Tool) (Verdict, error) {
	if c.reviewer == nil {
		return Verdict{}, errNoReviewer
	}
	v, err := c.reviewer.Review(ctx, t)
	if err != nil {
		c.report(source, t.Key, err)
		return v, err
	}
	if c.store != nil {
		if err := c.store.Save(ctx, source, v); err != nil {
			// The verdict is still good for this process.
			c.report(source, t.Key, err)
		}
	}
	c.mu.Lock()
	c.remember(catalogKey{source, t.Key}, v)
	c.mu.Unlock()
	return v, nil
}

func (c *Catalog) remember(k catalogKey, v Verdict) {
	if _, ok := c.cache[k]; !ok && len(c.cache) >= c.maxCache {
		c.evictLocked()
	}
	v.Stale = false
	c.cache[k] = v
}

// evictLocked frees a quarter of the cache, dropping verdicts that hold
// nothing before any that do: without a store, a dropped hold is gone until
// the tool is reviewed again.
func (c *Catalog) evictLocked() {
	target := len(c.cache) - c.maxCache*3/4
	for _, holds := range []bool{false, true} {
		for k, v := range c.cache {
			if target <= 0 {
				return
			}
			if v.Class.RequiresApproval() == holds {
				delete(c.cache, k)
				target--
			}
		}
	}
}

func (c *Catalog) report(source, key string, err error) {
	if c.onError != nil && err != nil {
		c.onError(source, key, err)
	}
}

// ErrBackoff means the tool's recent reviews failed and it is not sent to the
// model again until its backoff ends. Review returns the best verdict it has.
var ErrBackoff = errors.New("toolreview: tool review is backing off after failures")

type reviewerError string

func (e reviewerError) Error() string { return string(e) }

const errNoReviewer = reviewerError("toolreview: catalog has no reviewer")

func cancelled(err error) bool {
	return errors.Is(err, context.Canceled) || errors.Is(err, context.DeadlineExceeded)
}

func withDeclared(v Verdict, t Tool) Verdict {
	v.Declared = t.Declared
	return v
}

func max1(n int) int {
	if n < 1 {
		return 1
	}
	return n
}

func round3(f float64) float64 {
	return float64(int(f*1000+0.5)) / 1000
}

// Holds returns the entries whose review makes the tool need approval when
// its provider's own label does not: the verdicts that change a gate's
// decision. A compiled-in fallback usually needs only these; a tool missing
// from it is reviewed when first seen.
func (m Manifest) Holds() Manifest {
	out := Manifest{Policy: m.Policy, Model: m.Model, Entries: make(map[string]Entry)}
	for k, e := range m.Entries {
		if Max(e.Declared, e.Class).RequiresApproval() && !e.Declared.RequiresApproval() {
			out.Entries[k] = e
		}
	}
	return out
}
