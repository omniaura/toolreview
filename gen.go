package toolreview

import (
	"bytes"
	"fmt"
	"go/format"
	"io"
	"math"
	"sort"
	"strconv"
	"strings"
)

// manifestHeader starts the table WriteGo emits and ParseManifest reads.
const manifestHeader = "toolreview-manifest v1"

// WriteGo writes m as Go source declaring
//
//	var <name> = toolreview.MustParseManifest(`…`)
//
// in package pkg, so a program carries its verdicts compiled in. The verdicts
// are a tab-separated table, one per line and sorted by key, rather than a map
// literal: a catalog of thousands of entries stays a fraction of the size and
// a refresh diffs line by line.
func WriteGo(w io.Writer, pkg, name, source string, m Manifest) error {
	table, err := m.Table()
	if err != nil {
		return err
	}
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by toolreview gen; DO NOT EDIT.\n\n")
	fmt.Fprintf(&b, "package %s\n\n", pkg)
	fmt.Fprintf(&b, "import \"github.com/omniaura/toolreview\"\n\n")
	fmt.Fprintf(&b, "// %s holds the %d %s verdicts reviewed under %s.\n", name, len(m.Entries), oneLine(source), oneLine(m.Policy))
	fmt.Fprintf(&b, "var %s = toolreview.MustParseManifest(`%s`)\n", name, table)
	src, err := format.Source(b.Bytes())
	if err != nil {
		return fmt.Errorf("toolreview: format generated source: %w", err)
	}
	_, err = w.Write(src)
	return err
}

// Table renders m in the form ParseManifest reads:
//
//	toolreview-manifest v1	<policy>	<model>
//	<key>	<fingerprint>	<class>	<declared>	<risk>[	<entry policy>]
//
// Fields may not contain a tab, a newline or a backquote.
func (m Manifest) Table() (string, error) {
	var b strings.Builder
	for _, f := range []string{m.Policy, m.Model} {
		if err := tableField(f); err != nil {
			return "", err
		}
	}
	b.WriteString("\n" + manifestHeader + "\t" + m.Policy + "\t" + m.Model + "\n")
	keys := make([]string, 0, len(m.Entries))
	for k := range m.Entries {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	for _, k := range keys {
		e := m.Entries[k]
		for _, f := range []string{k, e.Fingerprint, e.Policy} {
			if err := tableField(f); err != nil {
				return "", err
			}
		}
		if k == "" || !e.Class.Valid() || (e.Declared != Unknown && !e.Declared.Valid()) || !validRisk(e.Risk) {
			return "", fmt.Errorf("toolreview: manifest entry %q is not a verdict", k)
		}
		b.WriteString(k + "\t" + e.Fingerprint + "\t" + string(e.Class) + "\t" + string(e.Declared) + "\t" +
			strconv.FormatFloat(e.Risk, 'f', -1, 64))
		if e.Policy != "" {
			b.WriteString("\t" + e.Policy)
		}
		b.WriteString("\n")
	}
	return b.String(), nil
}

func tableField(f string) error {
	if strings.ContainsAny(f, "\t\n\r`") || f != strings.TrimSpace(f) {
		return fmt.Errorf("toolreview: manifest field %q contains a tab, newline or backquote, or is padded", f)
	}
	return nil
}

func validRisk(r float64) bool { return !math.IsNaN(r) && r >= 0 && r <= 1 }

// ParseManifest reads the table Manifest.Table renders.
func ParseManifest(table string) (Manifest, error) {
	lines := strings.Split(strings.Trim(table, "\n"), "\n")
	head := strings.Split(lines[0], "\t")
	if len(head) != 3 || head[0] != manifestHeader {
		return Manifest{}, fmt.Errorf("toolreview: not a manifest table")
	}
	m := Manifest{Policy: head[1], Model: head[2], Entries: make(map[string]Entry, len(lines)-1)}
	for i, line := range lines[1:] {
		f := strings.Split(line, "\t")
		if len(f) != 5 && len(f) != 6 {
			return Manifest{}, fmt.Errorf("toolreview: manifest line %d has %d fields", i+2, len(f))
		}
		risk, err := strconv.ParseFloat(f[4], 64)
		if err != nil {
			return Manifest{}, fmt.Errorf("toolreview: manifest line %d: risk: %w", i+2, err)
		}
		e := Entry{Fingerprint: f[1], Class: Class(f[2]), Declared: Class(f[3]), Risk: risk}
		if len(f) == 6 {
			if f[5] == "" {
				return Manifest{}, fmt.Errorf("toolreview: manifest line %d has an empty entry policy", i+2)
			}
			e.Policy = f[5]
		}
		if f[0] == "" || !e.Class.Valid() || (e.Declared != Unknown && !e.Declared.Valid()) || !validRisk(risk) {
			return Manifest{}, fmt.Errorf("toolreview: manifest line %d is not a verdict", i+2)
		}
		if _, dup := m.Entries[f[0]]; dup {
			return Manifest{}, fmt.Errorf("toolreview: manifest line %d repeats %q", i+2, f[0])
		}
		m.Entries[f[0]] = e
	}
	return m, nil
}

// MustParseManifest is ParseManifest for generated code; it panics on a
// malformed table, which only a hand edit of a generated file can produce.
func MustParseManifest(table string) Manifest {
	m, err := ParseManifest(table)
	if err != nil {
		panic(err)
	}
	return m
}

func oneLine(s string) string {
	return strings.Join(strings.Fields(s), " ")
}
